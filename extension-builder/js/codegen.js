/**
 * Extension Builder - Code generator: model -> Studio/Extension-style Card({...}) source.
 * Also: nodeExpr() (handler-less expression for the canvas) and extractModel() (re-import).
 */
(function (global) {
  'use strict';

  const MODEL_TAG = '@oft-builder-model:';

  const q = (s) => "'" + String(s == null ? '' : s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\r?\n/g, '\\n') + "'";
  const num = (v, d = 0) => { const n = Number(v); return Number.isFinite(n) ? n : d; };
  const pad = (text, n) => text.split('\n').map(l => (l.trim() ? ' '.repeat(n) + l : l)).join('\n');
  const dedent = (code) => {
    const lines = String(code || '').replace(/\s+$/, '').split('\n');
    const indents = lines.filter(l => l.trim()).map(l => l.match(/^ */)[0].length);
    const m = indents.length ? Math.min(...indents) : 0;
    return lines.map(l => l.slice(m)).join('\n');
  };

  function parseOptions(text) {
    return String(text || '').split('\n').map(l => l.trim()).filter(Boolean).map(l => {
      const i = l.indexOf(':');
      return i < 0 ? { id: l, label: l } : { id: l.slice(0, i).trim(), label: l.slice(i + 1).trim() };
    });
  }

  function handlerCode(node, withHandlers) {
    const def = global.OFTBuilderPalette.PALETTE[node.type];
    if (!withHandlers || !def.handler) return null;
    const body = dedent(node.handler);
    if (!body.trim() && node.type !== 'button') return null;
    return `${def.handler.name}(${def.handler.params}) {\n${body.trim() ? pad(body, 2) + '\n' : ''}}`;
  }

  /** Returns a JS expression string for one node (children included). */
  function nodeExpr(node, withHandlers) {
    const p = node.props || {};
    const kids = () => (node.children || []).map(c => pad(nodeExpr(c, withHandlers), 2)).join(',\n');
    const obj = (entries) => {
      const lines = entries.filter(Boolean);
      return lines.length ? '{\n' + pad(lines.join(',\n'), 2) + '\n}' : '{}';
    };
    const withH = (entries) => { const h = handlerCode(node, withHandlers); return h ? entries.concat([h]) : entries; };

    switch (node.type) {
      case 'section':
        return p.subtitle ? `ui.section(${q(p.title)}, ${q(p.subtitle)})` : `ui.section(${q(p.title)})`;
      case 'text':
        return `ui.text(${obj([`text: ${q(p.text)}`, `variant: ${q(p.variant || 'label')}`])})`;
      case 'button':
        return `ui.button(${obj(withH([`label: ${q(p.label)}`, p.icon && `icon: ${q(p.icon)}`, p.title && `title: ${q(p.title)}`]))})`;
      case 'input':
        return `ui.input(${obj(withH([`type: ${q(p.type || 'text')}`, `value: ${q(p.value)}`, p.placeholder && `placeholder: ${q(p.placeholder)}`]))})`;
      case 'textarea':
        return `ui.textarea(${obj(withH([`value: ${q(p.value)}`, p.placeholder && `placeholder: ${q(p.placeholder)}`, `rows: ${num(p.rows, 4)}`]))})`;
      case 'switch':
        return `ui.switch(${obj(withH([`label: ${q(p.label)}`, `checked: ${!!p.checked}`]))})`;
      case 'slider':
        return `ui.slider(${obj(withH([`label: ${q(p.label)}`, `min: ${num(p.min)}`, `max: ${num(p.max, 100)}`, `step: ${num(p.step, 1)}`, `value: ${num(p.value, 50)}`]))})`;
      case 'segmented': {
        const opts = parseOptions(p.options).map(o => `{ id: ${q(o.id)}, label: ${q(o.label)} }`).join(', ');
        return `ui.segmented(${obj(withH([`label: ${q(p.label)}`, `options: [${opts}]`, `value: ${q(p.value)}`]))})`;
      }
      case 'grid':
        return `ui.grid({ cols: ${Math.max(1, num(p.cols, 3))} }, [${node.children && node.children.length ? '\n' + kids() + '\n' : ''}])`;
      case 'formRow':
        return `ui.formRow([${node.children && node.children.length ? '\n' + kids() + '\n' : ''}])`;
      default:
        return '/* unknown component */';
    }
  }

  const toB64 = (s) => btoa(unescape(encodeURIComponent(s)));
  const fromB64 = (s) => decodeURIComponent(escape(atob(s)));

  function generate(model) {
    const m = model.meta;
    const stmts = model.nodes.map(n => nodeExpr(n, true) + ';').join('\n');
    const shared = dedent(model.shared);
    const body = [shared, stmts].filter(s => s.trim()).join('\n\n');
    return [
      '/**',
      ` * OpenFishTools Extension - ${m.name} (.js)`,
      ' * Generated by Extension Builder. Place this file in Studio/Extension/.',
      ' */',
      'Card({',
      `  id: ${q(m.id)},`,
      `  name: ${q(m.name)},`,
      `  icon: ${q(m.icon)},`,
      `  description: ${q(m.description)},`,
      `  category: ${q(m.category)},`,
      `  defaultEnabled: ${m.defaultEnabled !== false},`,
      '',
      '  build(ui, ctx) {',
      body ? pad(body, 4) : '    // Add components on the canvas.',
      '  }',
      '});',
      '',
      `/* ${MODEL_TAG}${toB64(JSON.stringify(model))} */`,
      ''
    ].join('\n');
  }

  function extractModel(code) {
    const m = String(code).match(/@oft-builder-model:([A-Za-z0-9+/=]+)/);
    if (!m) return null;
    try {
      const d = JSON.parse(fromB64(m[1]));
      return d && d.meta && Array.isArray(d.nodes) ? d : null;
    } catch (_) { return null; }
  }

  global.OFTBuilderCodegen = { generate, nodeExpr, extractModel, parseOptions };
})(window);
